import { afterEach, expect, test, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { CommunicationSection } from '@/features/parents/components/CommunicationSection'
import { clearParentChat, getCommunicationGuides, getParentChat, sendParentChat, type ParentChatSnapshot } from '@/lib/api/communicationApi'
import { ApiError } from '@/lib/api/client'
import { setLocale } from '@/i18n'

vi.mock('@/lib/api/communicationApi', () => ({ getParentChat: vi.fn(), sendParentChat: vi.fn(), clearParentChat: vi.fn(), getCommunicationGuides: vi.fn() }))
vi.mock('@/hooks/useAuthedImage', () => ({ useAuthedImage: () => null }))
afterEach(() => { cleanup(); vi.resetAllMocks(); localStorage.clear(); sessionStorage.clear(); act(() => setLocale('zh')) })
const work = { sourceId: 'tree', createdAt: '2026-09-25T00:00:00Z', imageUrl: null, title: '树', observation: '画面中可以看到树。', evidenceIds: ['OBS-elements'], provenance: 'child' }
const turn = { id: 'request-0001', userText: '我也很累', reply: '每次都得你先忍住，确实很累。', createdAt: '2026-09-26T00:00:00Z', sourceId: null, sources: [] }
const state = (changes = {}): ParentChatSnapshot => ({ revision: 0, available: true, turns: [], memory: { works: [work], scannedCount: 1, limit: 50 }, ...changes })
const start = async (changes = {}) => {
  vi.mocked(getParentChat).mockResolvedValue(state(changes))
  const view = render(<CommunicationSection childName="小朋友" childId="C" token="T" />)
  await screen.findByRole('textbox', { name: '想说的话' })
  await screen.findByText('今天，有什么想聊聊的？')
  return view
}

test('the initial view keeps chat central and does not make unsolicited model calls or repeat the title', async () => {
  await start()
  expect(screen.queryByText('AI 沟通助手')).toBeNull()
  expect(screen.getByText('从画作找个话题').closest('details')?.open).toBe(false)
  expect(getCommunicationGuides).not.toHaveBeenCalled()
  expect(sendParentChat).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: /刚才没忍住/ }))
  const input = screen.getByRole('textbox') as HTMLTextAreaElement
  expect(input.value).toBe('刚才没忍住，冲孩子发了脾气')
  expect(sendParentChat).not.toHaveBeenCalled()
  fireEvent.keyDown(input, { key: 'Enter' })
  expect(sendParentChat).not.toHaveBeenCalled()
  vi.mocked(sendParentChat).mockResolvedValue({ revision: 1, turn })
  fireEvent.click(screen.getByRole('button', { name: '发送' }))
  await screen.findByText(turn.reply)
  expect(sendParentChat).toHaveBeenCalledWith('C', 'T', expect.objectContaining({ text: input.value || '刚才没忍住，冲孩子发了脾气', revision: 0, sourceId: null }), expect.any(AbortSignal))
})

test('artwork selection fills an editable draft and supplies the source only after explicit send', async () => {
  await start()
  fireEvent.click(screen.getByText('孩子的创作'))
  fireEvent.click(screen.getByRole('button', { name: /聊聊这幅画/ }))
  expect((screen.getByRole('textbox') as HTMLTextAreaElement).value).toContain('这幅画')
  expect(screen.getByText('这次聊 · 树')).toBeTruthy()
  expect(sendParentChat).not.toHaveBeenCalled()
  vi.mocked(sendParentChat).mockResolvedValue({ revision: 1, turn: { ...turn, sourceId: 'tree', sources: [work] } })
  fireEvent.click(screen.getByRole('button', { name: '发送' }))
  await screen.findByRole('button', { name: /参考作品/ })
  expect(vi.mocked(sendParentChat).mock.calls[0][2].sourceId).toBe('tree')
})

test('failed messages stay editable and keyboard retry reuses the same request ID', async () => {
  await start()
  vi.mocked(sendParentChat).mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce({ revision: 1, turn })
  fireEvent.change(screen.getByRole('textbox'), { target: { value: '我也很累' } })
  fireEvent.click(screen.getByRole('button', { name: '发送' }))
  await screen.findByRole('alert')
  expect((screen.getByRole('textbox') as HTMLTextAreaElement).value).toBe('我也很累')
  fireEvent.keyDown(screen.getByRole('textbox'), { key: 'Enter', ctrlKey: true })
  await screen.findByText(turn.reply)
  expect(vi.mocked(sendParentChat).mock.calls[1][2]).toEqual(vi.mocked(sendParentChat).mock.calls[0][2])
  expect(screen.queryByRole('alert')).toBeNull()
})

test('switching children aborts pending sends and ignores late answers', async () => {
  const view = await start()
  let finish!: (value: { revision: number; turn: typeof turn }) => void
  vi.mocked(sendParentChat).mockImplementationOnce(() => new Promise(resolve => { finish = resolve }))
  fireEvent.change(screen.getByRole('textbox'), { target: { value: '我也很累' } })
  fireEvent.click(screen.getByRole('button', { name: '发送' }))
  expect(screen.getByRole('status', { name: '正在回复…' })).toBeTruthy()
  view.rerender(<CommunicationSection childName="另一个孩子" childId="B" token="T" />)
  await screen.findByText('今天，有什么想聊聊的？')
  expect(vi.mocked(sendParentChat).mock.calls[0][3]?.aborted).toBe(true)
  await act(async () => finish({ revision: 1, turn }))
  expect(screen.queryByText(turn.reply)).toBeNull()
  expect(getParentChat).toHaveBeenLastCalledWith('B', 'T', 'zh', expect.any(AbortSignal))
})

test('clear requires a deliberate second click and preserves artwork memory', async () => {
  vi.mocked(getParentChat).mockResolvedValue(state({ revision: 1, turns: [turn] }))
  vi.mocked(clearParentChat).mockResolvedValue({ revision: 2 })
  render(<CommunicationSection childName="小朋友" childId="C" token="T" />)
  fireEvent.click(await screen.findByRole('button', { name: '清空聊天' }))
  expect(clearParentChat).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: '确认清空' }))
  await screen.findByText('今天，有什么想聊聊的？')
  expect(clearParentChat).toHaveBeenCalledWith('C', 'T', 1, expect.any(AbortSignal))
  expect(screen.queryByText(turn.reply)).toBeNull()
  fireEvent.click(screen.getByText('孩子的创作'))
  expect(screen.getByText('树')).toBeTruthy()
})

test('stale history reloads without automatically resending; the written message is retained', async () => {
  await start()
  vi.mocked(sendParentChat).mockRejectedValue(new ApiError(409, 'chat_changed'))
  vi.mocked(getParentChat).mockResolvedValue(state({ revision: 2 }))
  fireEvent.change(screen.getByRole('textbox'), { target: { value: '新的问题' } })
  fireEvent.click(screen.getByRole('button', { name: '发送' }))
  await screen.findByText('记录已更新，请确认后再发送。')
  await waitFor(() => expect(getParentChat).toHaveBeenCalledTimes(2))
  expect((screen.getByRole('textbox') as HTMLTextAreaElement).value).toBe('新的问题')
  expect(sendParentChat).toHaveBeenCalledTimes(1)
})

