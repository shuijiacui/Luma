test('guest history restores conversations and drafts, confirms deletion and persists across sessions', async () => {
  // jsdom does not implement native dialog focus management; browser QA covers it.
  HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', '') }
  HTMLDialogElement.prototype.close = function () { this.removeAttribute('open') }
  const view = render(<CommunicationSection childName="小朋友" isGuest />)
  fireEvent.change(screen.getByRole('textbox'), { target: { value: '刚才没忍住，冲孩子发了脾气' } })
  fireEvent.click(screen.getByRole('button', { name: '发送' }))
  expect(screen.getByRole('button', { name: '新对话' }).hasAttribute('disabled')).toBe(true)
  expect(screen.getByRole('button', { name: '历史记录' }).hasAttribute('disabled')).toBe(true)
  const reply = '那一下可能是气急了，吼完心里也不太舒服。刚才是发生了什么？'
  await screen.findByText(reply)
  fireEvent.change(screen.getByRole('textbox'), { target: { value: '还没发出去的话' } })
  fireEvent.click(screen.getByRole('button', { name: '新对话' }))
  expect(screen.getByText('今天，有什么想聊聊的？')).toBeTruthy()
  expect((screen.getByRole('textbox') as HTMLTextAreaElement).value).toBe('')
  fireEvent.click(screen.getByRole('button', { name: /想聊聊孩子最近的画/ }))
  fireEvent.click(screen.getByRole('button', { name: '发送' }))
  await screen.findByText(/最近有那幅小船，还有一片小森林/)
  fireEvent.click(screen.getByRole('button', { name: '历史记录' }))
  expect(screen.getByRole('dialog', { name: '历史记录' })).toBeTruthy()
  expect(screen.getAllByRole('button', { name: /^继续对话/ })).toHaveLength(2)
  fireEvent.click(screen.getByRole('button', { name: '继续对话：刚才没忍住，冲孩子发了脾气' }))
  expect(screen.queryByRole('dialog')).toBeNull()
  expect(screen.getByText(reply)).toBeTruthy()
  expect(screen.queryByText(/最近有那幅小船，还有一片小森林/)).toBeNull()
  expect((screen.getByRole('textbox') as HTMLTextAreaElement).value).toBe('还没发出去的话')
  view.unmount(); sessionStorage.clear()
  render(<CommunicationSection childName="小朋友" isGuest />)
  expect(screen.getByText(reply)).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: '历史记录' }))
  fireEvent.click(screen.getByRole('button', { name: '删除对话：刚才没忍住，冲孩子发了脾气' }))
  expect(screen.getAllByRole('button', { name: /^继续对话/ })).toHaveLength(2)
  fireEvent.click(screen.getByRole('button', { name: '取消' }))
  expect(screen.queryByText('删除后，这段对话无法恢复。')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: '删除对话：刚才没忍住，冲孩子发了脾气' }))
  fireEvent.click(screen.getByRole('button', { name: '确认删除' }))
  expect(screen.getAllByRole('button', { name: /^继续对话/ })).toHaveLength(1)
  fireEvent.click(screen.getByRole('button', { name: '删除对话：想聊聊孩子最近的画' }))
  fireEvent.click(screen.getByRole('button', { name: '确认删除' }))
  expect(screen.getByText('聊过的话，会留在这里')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: '关闭历史记录' }))
  expect(screen.getByText('今天，有什么想聊聊的？')).toBeTruthy()
  expect(getParentChat).not.toHaveBeenCalled()
  expect(sendParentChat).not.toHaveBeenCalled()
})
